#!/usr/bin/env python3
"""freshness.py: one place that checks every number and list shown on the Founder view, Status view and FounderView3D is current.
Runs every dispatcher cycle (run_batch.sh) before the pages are built. Writes cache/freshness.json (the pages read it) and one line in
orchestrator-log.md when a NEW finding appears. Auto-fixes only derived data (owner_hold lines for merged PRs, closed issues in priorities.json,
pipeline.txt rebuilt from priorities.json). Everything hand-written is flagged for the Orchestrator's daily/weekly review, never edited here.
Severity: stale = the page is showing something wrong or out of date; review = hand-written content past its review age.
ponytail: rules are plain Python below; to cover a new data source add one function and append it to CHECKS."""
import datetime, json, os, re, time
D = os.path.dirname(os.path.abspath(__file__)); NOW = time.time()
def P(f): return os.path.join(D, f)
def rd(f, d=""):
    try: return open(P(f), encoding="utf-8").read()
    except OSError: return d
def jl(f, d):
    try: return json.loads(rd(f) or "null") or d
    except ValueError: return d
def age(f):
    try: return NOW - os.path.getmtime(P(f))
    except OSError: return None
def hrs(s): return "%.1f h" % (s / 3600) if s >= 5400 else "%d min" % round(s / 60)
def atomic(f, text):
    open(P(f) + ".tmp", "w", encoding="utf-8").write(text); os.replace(P(f) + ".tmp", P(f))
F = []   # findings
def add(key, sev, source, what, fix, fixed=False): F.append(dict(key=key, sev=sev, source=source, what=what, fix=fix, fixed=fixed))
issues = {str(i["number"]): i for i in jl("cache/issues_live.json", [])}
gl = rd("github.log")
merged = set(re.findall(r"PR #(\d+) merged", gl))
def merge_times():
    out = []
    for m in re.finditer(r"- (\S+Z) PR #(\d+) merged", gl):
        try: out.append((datetime.datetime.strptime(m.group(1), "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=datetime.timezone.utc).timestamp(), m.group(2)))
        except ValueError: pass
    return out
# ---- 1. is the machinery that refreshes data alive? ----
def c_liveness():
    for f, mx, name in (("cache/loop.beat", 180, "Dispatcher heartbeat"), ("cache/health.json", 300, "Agent counts"), ("cache/issues_live.json", 900, "Issue list"),
                        ("cache/prs_live.json", 900, "Open PR list"), ("FounderStatus.html", 600, "Founder view page"), ("status.html", 600, "Status view page"),
                        ("FounderView3D.html", 600, "FounderView3D page")):
        a = age(f)
        if a is None: add("missing:" + f, "stale", name, f + " does not exist", "Start the dispatcher (Start on the Founder view)"); continue
        if a > mx: add("old:" + f, "stale", name, "last refreshed %s ago (should be under %s)" % (hrs(a), hrs(mx)), "Check the dispatcher is running; restart it from the Founder view if not")
    if os.path.exists(os.path.expanduser("~/.appstoreconnect/config.json")):
        a = age("cache/fb.stamp")
        if a is not None and a > 3 * 3600: add("old:fb", "stale", "test build feedback", "last pulled %s ago" % hrs(a), "Check pull_feedback.py output in cache/fb.log")
# ---- 2. derived lists that must match reality (auto-fixed) ----
def c_owner_hold():
    lines = rd("owner_hold.txt").split("\n"); keep, gone = [], []
    for l in lines:
        m = re.match(r"\s*(\d+)\s*#", l)
        if m and m.group(1) in merged: gone.append(m.group(1))
        else: keep.append(l)
    if gone:
        atomic("owner_hold.txt", "\n".join(keep)); add("hold:" + ",".join(gone), "review", "Waiting-for-you list", "removed merged PRs " + ", ".join("#" + g for g in gone), "none needed", True)
def c_priorities():
    pr = jl("priorities.json", {}); order = pr.get("order", []); tiers = pr.get("tiers", {})
    closed = [n for n in order if issues.get(str(n), {}).get("state") == "CLOSED"]
    if closed and issues:
        pr["order"] = [n for n in order if n not in closed]; pr["tiers"] = {k: v for k, v in tiers.items() if int(k) not in closed}
        atomic("priorities.json", json.dumps(pr)); add("prio:" + ",".join(map(str, closed)), "review", "Prioritise order", "dropped closed issues " + ", ".join("#%s" % n for n in closed), "none needed", True)
def c_pipeline():
    """pipeline.txt is derived from priorities.json (the Prioritise tab), so the Pipeline tab can never show retired waves."""
    pr = jl("priorities.json", {}); order = pr.get("order", []); tiers = pr.get("tiers", {})
    if not order or not issues: return
    W = {"P0": ("Wave 1: now", "Highest priority: runs first"), "P1": ("Wave 2: next", "Next in line"), "P2": ("Wave 3: later", "When time allows")}
    rows = ["# AUTO-GENERATED by freshness.py from priorities.json (change priorities in the Prioritise tab, not here). One row per open, ranked issue."]
    for tier in ("P0", "P1", "P2"):
        for n in order:
            if tiers.get(str(n)) != tier: continue
            i = issues.get(str(n))
            if i and i.get("state") == "OPEN": rows.append("%s | %s | %s | %s" % (W[tier][0], n, re.sub(r"\s*\|\s*", " / ", i["title"])[:110], W[tier][1]))
    text = "\n".join(rows) + "\n"
    if text != rd("pipeline.txt"): atomic("pipeline.txt", text)
# ---- 3. hand-written data that goes out of date ----
def c_last_build():
    lb = [l for l in rd("last_build.txt").splitlines() if l.strip() and not l.startswith("#")]
    if not lb: add("lastbuild:none", "stale", "Next build page", "last_build.txt is empty", "Record the last test build upload"); return
    try: t = datetime.datetime.strptime(lb[0].split("|")[0].strip(), "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=datetime.timezone.utc).timestamp()
    except ValueError: add("lastbuild:fmt", "stale", "Next build page", "last_build.txt first line is not 'UTC time | label'", "Fix the format"); return
    n = sum(1 for ts, _ in merge_times() if ts > t)
    if NOW - t > 72 * 3600 and n >= 8:
        add("lastbuild:old", "stale", "Next build page + release gates", "last_build.txt says '%s' (%s ago) but %d PRs have merged since" % (lb[0].split("|")[1].strip(), hrs(NOW - t), n), "If a newer build went out, add its line to last_build.txt; the gates that use @buildN turn green from it")
def c_targets():
    for l in rd("targets.txt").splitlines():
        p = [x.strip() for x in l.split("|")]
        if l.startswith("#") or len(p) < 3: continue
        try: d = datetime.datetime.strptime(p[1], "%Y-%m-%d").timestamp() + 86400
        except ValueError: continue
        if d < NOW and p[0] != "launch": add("target:" + p[1] + p[2][:20], "stale", "Overview targets", "target '%s' (%s) is in the past" % (p[2], p[1]), "Set the next date or retire the line in targets.txt")
def c_release():
    for l in rd("release.txt").splitlines():
        if l.startswith("#") or l.count("|") < 3: continue
        for n in re.findall(r"#(\d+)", l.split("|")[2]):
            if issues and n not in issues: add("gate:" + n, "stale", "Release gates", "gate #%s does not exist on GitHub (%s)" % (n, l.split("|")[0].strip()), "Remove or correct the gate in release.txt")
def c_owner_tasks():
    def norm(t): return re.sub(r"^owner:\s*", "", t.strip().lower())
    gh = [norm(i["title"]) for i in issues.values() if i.get("state") == "OPEN" and i["title"].lower().startswith("owner")]
    txt = [norm(l.split("|", 1)[1]) for l in rd("owner_tasks.txt").splitlines() if l.startswith("Owner to-do|")]
    def same(a, b): return a[:30] == b[:30] or a.startswith(b) or b.startswith(a)
    for t in txt:
        if issues and not any(same(t, g) for g in gh): add("otask:" + t[:30], "review", "Needs-you list", "to-do '%s...' has no open 'Owner:' issue on GitHub" % t[:40], "Close it in owner_tasks.txt if done, or open an Owner issue")
    for g in gh:
        if not any(same(t, g) for t in txt): add("otask2:" + g[:30], "review", "Needs-you list", "open Owner issue '%s...' is not in owner_tasks.txt" % g[:40], "Fine if the page reads GitHub; add it so CompanyOS answers can find it")
MANUAL = [("optimisations.txt", "Optimisation tab"), ("roadmap.txt", "Roadmap epics"), ("success.txt", "Success measures"), ("journey.txt", "User journey"),
          ("marketing.txt", "Marketing lane"), ("estimates.txt", "Estimates"), ("ship.txt", "Build checklist")]
def c_manual():
    for f, name in MANUAL:
        a = age(f)
        if a is not None and a > 7 * 86400: add("manual:" + f, "review", name, "%s not edited for %d days" % (f, a // 86400), "Weekly review: confirm it is still true, then save it (touch) or edit it")
def c_summary():
    a = age("summary.txt")
    if a is not None and a > 86400: add("summary:old", "review", "Orchestrator note", "summary.txt is %s old (hidden on the Status page after 15 minutes)" % hrs(a), "Orchestrator refreshes it in the daily review")
CHECKS = [c_liveness, c_owner_hold, c_priorities, c_pipeline, c_last_build, c_targets, c_release, c_owner_tasks, c_manual, c_summary]
for c in CHECKS:
    try: c()
    except Exception as ex: add("check:" + c.__name__, "stale", "freshness.py", "%s failed: %s" % (c.__name__, ex), "Fix freshness.py")
bad = [f for f in F if not f["fixed"]]
out = dict(ts=int(NOW), checks=len(CHECKS), stale=sum(1 for f in bad if f["sev"] == "stale"), review=sum(1 for f in bad if f["sev"] == "review"), items=F)
atomic("cache/freshness.json", json.dumps(out))
seen = set(jl("cache/freshness.seen.json", [])); cur = {f["key"] for f in F}; new = [f for f in F if f["key"] not in seen]
if new:
    with open(P("orchestrator-log.md"), "a", encoding="utf-8") as g:
        for f in new[:6]: g.write("- %s (freshness) %s: %s%s\n" % (time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(NOW)), f["source"], f["what"], " [auto-fixed]" if f["fixed"] else ""))
atomic("cache/freshness.seen.json", json.dumps(sorted(cur)))
print("freshness: %d stale, %d to review, %d auto-fixed" % (out["stale"], out["review"], sum(1 for f in F if f["fixed"])))
